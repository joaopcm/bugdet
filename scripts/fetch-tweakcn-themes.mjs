function toTitleCase(slug) {
  return slug
    .split("-")
    .map((w) => w.charAt(0).toUpperCase() + w.slice(1))
    .join(" ");
}

function normalize(item) {
  return {
    name: item.name,
    title: item.title || toTitleCase(item.name),
    description: item.description || "",
    cssVars: {
      theme: item.cssVars?.theme ?? {},
      light: item.cssVars?.light ?? {},
      dark: item.cssVars?.dark ?? {},
    },
  };
}

async function main() {
  console.log(`Fetching ${REGISTRY_URL}`);
  const res = await fetch(REGISTRY_URL);
  if (!res.ok) {
    throw new Error(`Registry fetch failed: ${res.status}`);
  }
  const registry = await res.json();

  const presets = [MATSU, ...registry.items.map(normalize)];

  const banner =
    "// Auto-generated by scripts/fetch-tweakcn-themes.mjs. Do not edit by hand.";
  const body = `${banner}

import type { Preset } from "./types";

export const PRESETS: readonly Preset[] = ${JSON.stringify(presets, null, 2)} as const;

export const PRESET_SLUGS = PRESETS.map((p) => p.name) as readonly string[];
`;

  writeFileSync(OUT_PATH, body);
  console.log(`Wrote ${presets.length} presets to ${OUT_PATH}`);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
